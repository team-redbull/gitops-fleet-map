    pg = page(); pg.goto(E + "#tab=clusters")
    for b in pg.locator("button.shb").all():
        b.click()
    pg.click("#foldall")
    pg.locator("button.shs").first.click(); pg.wait_for_timeout(300); pg.keyboard.press("Escape")
    for b in pg.locator("td.cell button.cb").all()[:8]:
        b.click(); pg.wait_for_timeout(120)
        for c in pg.locator("#sheet button.chh").all()[:2]:
            c.click()
        pg.keyboard.press("Escape")
    ok(not pg.dialogs and not pg.errs and pg.locator("img").count() == 0, "hostile names inert in fold headers, site sheet and chart rows")

    # 16. day1-registered tenants: missing status, notes, .yml and upgrade warnings (copy set: ta/tb/tc)
    pg = page(); pg.goto(X)
    ok(pg.locator(".tile .top").all_inner_texts() == ["Onboarded", "Missing", "Stale", "Available", "Conflicts", "Not in day2"] and pg.locator(".tile").nth(1).locator(".num").inner_text() == "3", "Missing tile appears when day1 registers clusters; fleet total counts it")
    ok("Missing: day1 registered it" in pg.inner_text("#legend") and "Missing only" in pg.locator("#fs").inner_text(), "legend and status filter know Missing")
