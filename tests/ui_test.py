    pg = page(); pg.goto(H + "#tab=clusters")
    pg.locator("[data-k='[\"ocp4-prod-a-site1\",\"acme\"]']").click(); pg.wait_for_timeout(350)
    pg.locator("#sheet li:has(> button.chh .cn:text-is('vals')) button.chh").click()
    t = pg.inner_text("#sheet")
