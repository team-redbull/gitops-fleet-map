#!/usr/bin/env python3
"""UI checks. Usage: ui_test.py DAY1_DIR NODAY1_DIR EDGE_DIR PROV_DIR HIDDEN_DIR MISSING_DIR CONFLICT_DIR (generated output dirs with index.html)."""
import json, sys, urllib.parse
from playwright.sync_api import sync_playwright

A, B, E, P, H, X = (f"file://{d}/index.html" for d in sys.argv[1:7])
fails = []


def ok(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond:
        fails.append(msg)


with sync_playwright() as p:
    br = p.chromium.launch()

    def page(w=1440, h=900, **kw):
        ctx = br.new_context(viewport={"width": w, "height": h}, **kw)
        pg = ctx.new_page()
        pg.errs, pg.dialogs = [], []
        pg.on("console", lambda m: pg.errs.append(m.text) if m.type == "error" else None)
        pg.on("pageerror", lambda e: pg.errs.append(str(e)))
        pg.on("dialog", lambda d: (pg.dialogs.append(d.message), d.dismiss()))
        return pg

    count = lambda pg: pg.inner_text("#count")
    nav = lambda pg, k: pg.click(f"#sitelist .ni[data-site='{k}']")

    # 1. loads cleanly, with and without day1
    for name, u in (("day1", A), ("no day1", B), ("edge set", E)):
        pg = page(); pg.goto(u)
        ok(not pg.errs and pg.locator("tr.r").count() > 0, f"loads without console/page errors ({name})")
    pg = page(); pg.goto(B)
    ok("no day1 data" in pg.inner_text("#banner"), "no-day1 banner shown without day1")
    pg.goto(A)
    ok(pg.locator("#banner .banner").count() == 0, "no banner with day1")
    ok("Built from local files" in pg.inner_text("#foot") and "no commit" not in pg.inner_text("#foot"), "footer says built from local files once")

    # 2. tenant + hash
    ok(pg.get_attribute("#tab-clusters", "aria-selected") == "true" and pg.inner_text("#ctx-t") == "All sites", "All tenants view opens on All clusters")
    ok("Updated" in pg.inner_text("#gen") and pg.get_attribute("#gen", "title").endswith("UTC"), "freshness chip: relative text, absolute time in title")
    pg.select_option("#tenant", "random")
    ok(pg.evaluate("location.hash") == "#tenant=random", "picking a tenant sets the hash")
    ok(pg.get_attribute("#tab-actions", "aria-selected") == "true" and pg.inner_text("#ctx-t") == "All sites · random", "tenant with work opens on Action items")
    pg.click("#tab-clusters")
    ok(pg.evaluate("location.hash") == "#tenant=random&tab=clusters", "tab is kept in the hash")
    ok(pg.locator("th.sel").inner_text() == "random" and pg.locator("#m thead th").nth(4).get_attribute("class") == "sel", "selected tenant column highlighted and first")
    pg2 = page(); pg2.goto(A + "#tenant=random&tab=clusters")
    ok(pg2.input_value("#tenant") == "random" and pg2.inner_text("#ctx-t") == "All sites · random" and pg2.get_attribute("#tab-clusters", "aria-selected") == "true", "reload restores tenant and tab")
    pg2.goto(A + "#tenant=random&tab=bogus"); pg2.reload()
    ok(pg2.get_attribute("#tab-actions", "aria-selected") == "true" and not pg2.errs, "unknown tab falls back to the default")
    pg3 = page(); pg3.goto(A + "#tenant=nope")
    ok(pg3.input_value("#tenant") == "" and pg3.inner_text("#ctx-t") == "All sites" and not pg3.errs, "unknown tenant hash falls back to All tenants")
    pg.select_option("#tenant", "")
    ok("tenant" not in pg.evaluate("location.hash") and "tab" not in pg.evaluate("location.hash"), "All tenants clears the hash")
    pg.focus("#tab-clusters"); pg.keyboard.press("ArrowRight")
    ok(pg.get_attribute("#tab-conflicts", "aria-selected") == "true" and pg.evaluate("document.activeElement.id") == "tab-conflicts", "arrow keys move between tabs")
    ok(pg.locator("#conf-n").get_attribute("class") == "badge red" and pg.inner_text("#conf-n") == "1", "conflict count badge is red when above 0")
    pg.click("#tab-clusters")

    # 3. filters
    pg = page(); pg.goto(A)
    ok(count(pg) == "Showing 10 of 10 clusters" and pg.locator("#clr").is_hidden(), "all rows shown, Clear hidden when unfiltered")
    pg.fill("#q", "hc01")
    ok(count(pg) == "Showing 1 of 10 clusters" and pg.locator("tr.r.hosted").count() == 1, "search narrows rows and count")
    pg.fill("#q", "")
    pg.select_option("#fs", "stale")
    ok(count(pg) == "Showing 2 of 10 clusters", "status filter: stale only")
    pg.select_option("#fs", "conflict")
    ok(count(pg) == "Showing 1 of 10 clusters", "status filter: conflicts only")
    pg.select_option("#fs", "all"); pg.select_option("#fenv", "prep")
    ok(count(pg) == "Showing 3 of 10 clusters", "env filter")
    pg.select_option("#fenv", ""); nav(pg, "site1")
    ok(count(pg) == "Showing 9 of 9 clusters", "site scope (prod-hub has no site, so it drops out)")
    pg.fill("#q", "zzzz")
    ok(pg.locator(".empty").is_visible() and count(pg) == "Showing 0 of 9 clusters", "empty state shown")
    pg.locator(".empty button").click()
    ok(count(pg) == "Showing 9 of 9 clusters" and pg.input_value("#q") == "" and pg.get_attribute("#sitelist .ni[data-site=site1]", "aria-current") == "page", "empty-state Clear filters resets filters but keeps the site")
    nav(pg, "")
    pg.fill("#q", "zzzz"); pg.click("#clr")
    ok(count(pg) == "Showing 10 of 10 clusters", "toolbar Clear filters resets")

    # 3b. summary tiles filter
    pg.goto(A)
    tile = lambda n: pg.locator(".tile").nth(n)
    ok([tile(i).locator(".num").inner_text() for i in range(4)] == ["9", "2", "6", "1"], "fleet tiles: onboarded/stale/available/conflicts totals")
    tile(1).click()
    ok(tile(1).get_attribute("aria-pressed") == "true" and count(pg) == "Showing 2 of 10 clusters" and pg.input_value("#fs") == "stale", "stale tile filters the matrix and shows pressed")
    tile(1).click()
    ok(tile(1).get_attribute("aria-pressed") == "false" and count(pg) == "Showing 10 of 10 clusters", "pressing the tile again clears it")
    pg.select_option("#tenant", "team-x")
    ok([pg.locator(".tile").nth(i).locator(".num").inner_text() for i in range(4)] == ["7", "1", "1", "1"], "tenant tiles show that tenant's counts")
    pg.goto(A)

    # 4. keyboard: Enter opens the side sheet, Esc closes it and returns focus
    pg.focus("td.cell button.cb")
    pg.keyboard.press("Enter")
    ok(pg.locator("#sheet.open").count() == 1 and pg.evaluate("document.activeElement.closest('#sheet') !== null") and pg.locator('td.cell button.cb[aria-expanded=true]').count() == 1, "Enter opens the side sheet, focus moves into it")
    pg.wait_for_timeout(400)
    box = pg.locator("#sheet").bounding_box()
    ok(box["x"] + box["width"] <= 1440 and box["x"] > 900 and any(w in pg.inner_text("#sheet") for w in ("Onboarded", "Available")), "sheet slid in on the right and shows status")
    pg.keyboard.press("Escape")
    ok(pg.locator("#sheet.open").count() == 0 and pg.evaluate("document.activeElement.getAttribute('aria-expanded')") == "false" and pg.evaluate("document.activeElement.classList.contains('cb')"), "Esc closes the sheet and focus returns to the cell")
    pg.locator("td.cell button.cb").first.click(); pg.click("#sclose")
    ok(pg.locator("#sheet.open").count() == 0, "close button dismisses the sheet")

    # 5. copy button (clipboard granted, then clipboard missing)
    pg = page(permissions=["clipboard-read", "clipboard-write"]); pg.goto(A + "#tenant=team-x")
    li = pg.locator(".acts li").first
    path = li.locator("code").first.inner_text()
    li.locator("button.copy").first.click()
    ok(pg.evaluate("navigator.clipboard.readText()") == path and li.locator("button.copy").first.inner_text() == "Copied", "copy button puts the path on the clipboard")
    pg = page(); pg.add_init_script("Object.defineProperty(navigator,'clipboard',{value:undefined})"); pg.goto(A + "#tenant=team-x")
    pg.locator(".acts li button.copy").first.click()
    ok(pg.evaluate("getSelection().toString()") == path, "without clipboard API the path gets selected")

    # 6. hostile names
    hostile = json.load(open(sys.argv[3] + "/inventory.json"))["tenants"]
    xt = next(t for t in hostile if t.startswith("<img"))
    pg = page(); pg.goto(E + "#tenant=" + urllib.parse.quote(xt))
    for b in pg.locator(".rowbtn").all()[:4]:
        b.click(); pg.keyboard.press("Escape")
    for b in pg.locator("button.copy").all()[:3]:
        b.click()
    pg.click("#tab-clusters")
    for b in pg.locator("td.cell button.cb").all()[:6]:
        b.click(); pg.keyboard.press("Escape")
    pg.select_option("#tenant", "")
    pg.locator("td.nm button.cb").first.click()
    pg.wait_for_timeout(400)
    body = pg.inner_text("body")
    ok(not pg.dialogs and not pg.errs, "hostile names execute nothing (no dialog, no errors)")
    ok(pg.locator("img").count() == 0, "no injected <img> elements")
    ok("<img src=x onerror=alert(2)>" in body and "quote's" in body, "hostile names render as text")
    ok(xt in pg.locator("#tenant option").all_inner_texts(), "hostile tenant name is a picker option")

    # 7. malformed files
    pg = page(); pg.goto(E)
    ok("Some files could not be read (5)" in pg.inner_text("#banner") and "alpha/defaults/mces/exclusions.yaml" in pg.text_content("#banner"), "malformed files: page renders and lists warnings")
    pg.goto(A)
    ok("could not be read" not in pg.inner_text("#banner"), "no warning note on clean fixtures")

    # 8. duplicate folders and env mismatch
    pg = page(); pg.goto(E + "#tenant=alpha")
    st = pg.inner_text("#area")
    ok("ocp4-prod-dup-site1" in st and "folder exists twice: sites/site1/prod/mces/ocp4-prod-mce-site1-a/ocp4-prod-dup-site1/, sites/site1/prod/mces/ocp4-prod-mce-site1-b/ocp4-prod-dup-site1/" in st, "duplicate hosted folders listed as stale with both paths")
    ok("ocp4-prod-both-site1" in st and "sites/site1/prod/upi/ocp4-prod-both-site1/" in st, "hosted+UPI duplicate listed as stale")
    pg.click("#tab-clusters")
    pg.locator('[data-k=\'["ocp4-prod-dup-site1","alpha"]\']').click()
    ok("Stale" in pg.inner_text("#sheet") and "folder exists twice" in pg.inner_text("#sheet"), "duplicate cell opens the sheet with its reason")
    pg.keyboard.press("Escape")
    pg.select_option("#tenant", "beta")
    ok("env prep" in pg.inner_text("#area") and "env prod" in pg.inner_text("#area") and "sites/site1/prod/mces/ocp4-prep-mce-site1-a/ocp4-prep-envy-site1/" in pg.inner_text("#area"), "env mismatch listed as stale with the tenant's real folder")

    # 9. mobile: no horizontal page scroll
    for name, u in (("day1", A + "#tenant=team-x"), ("no day1", B), ("edge", E + "#tenant=" + urllib.parse.quote(xt)), ("edge fleet", E)):
        pg = page(390, 844); pg.goto(u)
        ok(pg.evaluate("document.documentElement.scrollWidth") <= 390, f"no horizontal page scroll at 390px ({name}, first view)")
        pg.click("#tab-clusters")
        pg.locator("td.cell button.cb").first.click()
        pg.wait_for_timeout(400)
        bx = pg.locator("#sheet").bounding_box()
        ok(pg.evaluate("document.documentElement.scrollWidth") <= 390 and bx["width"] <= 390 and bx["y"] > 100 and bx["y"] + bx["height"] <= 845, f"no horizontal page scroll at 390px, bottom sheet fits ({name})")

    # 10. foldable site sections (prov set: site1, site4, prod-hub)
    pg = page(); pg.goto(P + "#tab=clusters")
    shb = lambda k: pg.locator(f"button.shb[data-fold='{k}']")
    ok(pg.locator("button.shb").count() == 3 and all(pg.locator("button.shb").nth(i).get_attribute("aria-expanded") == "true" for i in range(3)) and "Management hub" in pg.locator("button.shb").last.inner_text(), "site sections: one button header per site plus Management hub, all open")
    n0 = pg.locator("tr.r").count()
    ok(pg.evaluate("getComputedStyle(document.querySelector('tr.site td')).position") == "sticky", "site header is sticky")
    shb("site1").click()
    ok(shb("site1").get_attribute("aria-expanded") == "false" and pg.locator("tr.r").count() < n0 and "in collapsed sites" in count(pg) and pg.evaluate("location.hash") == "#tab=clusters&fold=site1" and pg.evaluate("document.activeElement.dataset.fold") == "site1", "folding a site hides its rows, writes fold= to the hash, keeps focus on the header")
    ok(pg.locator("tr.site .mini .pill").count() > 0 and "clusters" in shb("site4").inner_text(), "header shows cluster count and status counts")
    shb("site1").focus(); pg.keyboard.press("Enter")
    ok(shb("site1").get_attribute("aria-expanded") == "true" and pg.locator("tr.r").count() == n0, "Enter on the header unfolds")
    pg.keyboard.press("Space")
    ok(shb("site1").get_attribute("aria-expanded") == "false", "Space on the header folds")
    pg2 = page(); pg2.goto(P + "#tab=clusters&fold=site4,site1")
    ok(pg2.locator("button.shb[data-fold=site4]").get_attribute("aria-expanded") == "false" and pg2.locator("button.shb[data-fold=site1]").get_attribute("aria-expanded") == "false" and pg2.locator("button.shb[data-fold=_hub]").get_attribute("aria-expanded") == "true" and pg2.locator("tr.r").count() == 1, "reload restores folded sites from the hash")
    pg2.goto(P + "#tab=clusters&fold=bogus"); pg2.reload()
    ok(pg2.locator("tr.r").count() == n0 and not pg2.errs, "unknown site in fold= is ignored")
    ok(pg.inner_text("#foldall") == "Collapse all", "toolbar offers Collapse all")
    pg.click("#foldall")
    ok(pg.inner_text("#foldall") == "Expand all" and pg.locator("tr.r").count() == 0 and pg.evaluate("location.hash") == "#tab=clusters&fold=_hub,site1,site4", "Collapse all folds every section and records it")
    pg.click("#foldall")
    ok(pg.locator("tr.r").count() == n0 and pg.evaluate("location.hash") == "#tab=clusters" and pg.inner_text("#foldall") == "Collapse all", "Expand all unfolds and clears the hash")
    nav(pg, "site4")
    ok(pg.locator("button.shb").count() == 0 and pg.locator("tr.site").count() >= 1 and pg.is_hidden("#foldall"), "one site: env sections replace the site fold headers")
    nav(pg, "")
    pg.locator("button.shs[data-site=site1]").click(); pg.wait_for_timeout(400)
    sh = pg.inner_text("#sheet")
    ok(pg.locator("#sheet.open").count() == 1 and "Site site1" in sh and "Applied to every cluster at this site" in sh and "sites/site1/values.yaml" in sh and "sites/site1/prod/values.yaml" in sh and "2 keys set" in sh and "feeds" in sh and "not present" not in sh, "site sheet lists the site files that exist, keys, what they feed")
    pg.locator("#sheet summary").first.click()
    ok("siteonly" in pg.inner_text("#sheet") and pg.locator("button.shs[aria-expanded=true]").count() == 1, "site sheet shows leaf key paths; header button marked expanded")
    pg.keyboard.press("Escape")
    ok(pg.locator("#sheet.open").count() == 0 and pg.evaluate("document.activeElement.dataset.site") == "site1", "Esc closes the site sheet and returns focus to the header button")
    ok(not pg.errs and not pg2.errs, "fold and site sheet: no console errors")

    # 11. provenance in the cell sheet
    pg = page(permissions=["clipboard-read", "clipboard-write"]); pg.goto(P + "#tab=clusters")
    pg.locator("[data-k='[\"ocp4-prod-a-site1\",\"acme\"]']").click(); pg.wait_for_timeout(350)
    row = lambda n: pg.locator(f"#sheet li:has(> button.chh .cn:text-is('{n}'))")
    ok(pg.locator("#sheet button.chh").count() == 5 and all(b.get_attribute("aria-expanded") == "false" for b in pg.locator("#sheet button.chh").all()) and pg.locator("#sheet .chb:visible").count() == 0, "chart rows start closed")
    hd = row("overr").locator("button.chh").inner_text()
    ok("default · hosted-clusters" in hd and "fleet-main" in hd and "Fleet default (hosted clusters)" in hd and row("overr").locator(".tg.warn").inner_text().strip() == "1", "closed header: origin badge, version chip with source, warning count")
    ok("own" in row("pinned").locator("button.chh").inner_text() and "release-4.16.27" in row("pinned").locator("button.chh").inner_text() and row("pinned").locator(".tg.warn").count() == 0, "own chart: own badge, pin version, no warning badge")
    row("vals").locator("button.chh").click()
    b = row("vals").locator(".chb")
    ok(b.is_visible() and row("vals").locator("button.chh").get_attribute("aria-expanded") == "true" and b.locator("ol.lad").count() == 2, "expanding shows both layer ladders")
    bt = b.inner_text()
    ok(all(x in bt for x in ("Team default", "Site site1", "Site site1 · prod", "Fleet default for prod", "Fleet default for this cluster", "Cluster-wide")) and not any(x in bt for x in ("OCP 4.16.27 pin", "MCE-wide", "This cluster's chart")) and "values-ocp4-prod-a-site1.yaml" in bt, "values ladder shows the layers that exist, with labels and paths")
    ok(b.locator("ol.lad").nth(1).locator("li.absent").count() == 0 and b.locator("ol.lad").nth(1).locator("li").count() < 10 and "not present" not in bt and "applied · " in bt, "only layers that exist are listed, with their key counts")
    pr = b.locator("ol.lad").nth(1).locator(".pn").all_inner_texts()
    ok(pr == sorted(pr, key=int) and pr[0] == "1" and "2" not in pr and "3" in pr, "ladder numbers are real priorities: gaps where a layer has no file")
    ea = b.locator(".eff li", has=pg.locator("code:text-is('a')")).first
    ok("cluster" in ea.inner_text() and "set by Cluster-wide" in ea.inner_text() and "overrode Team default, Site site1" in ea.inner_text(), "effective value shows value, set by, overrode")
    ok("••• (hidden)" in bt and "hunter2" not in pg.inner_text("body"), "secret value redacted in the page")
    ok("auto-sync" in bt and "Repo" in bt and "set by Team default" in bt, "summary: repo, version source, sync")
    ok(b.locator(".flt").count() == 1, "filter box when more than 15 keys")
    b.locator(".flt").fill("k1")
    ok(b.locator(".flt + .eff li:visible").count() == 5, "filter narrows the effective keys")
    cp = b.locator("ol.lad li").first.locator("button.copy"); cp.click()
    ok(pg.evaluate("navigator.clipboard.readText()") == "operators/vals/vals.yaml", "ladder copy button copies the layer path")
    row("overr").locator("button.chh").click(); row("kyv").locator("button.chh").click(); row("broken").locator("button.chh").click()
    ok("sets targetRevision above the OCP 4.16.27 pin" in row("overr").inner_text() and row("overr").locator(".callout.warn").is_visible(), "override warning shown as inline alert")
    ok("renders an empty repoURL" in row("kyv").inner_text() and "not set, renders empty" in row("kyv").inner_text(), "repoUrl casing warning shown")
    ok("not valid YAML" in row("broken").inner_text(), "parse error shown on the layer")
    pg.keyboard.press("Escape")
    pg.locator("[data-k='[\"ocp4-prod-a-site1\",\"acme\"]']").click(); pg.wait_for_timeout(350)
    ok(row("vals").locator("button.chh").get_attribute("aria-expanded") == "true", "expanded rows survive closing and reopening the sheet")
    pg.keyboard.press("Escape")
    pg.locator("[data-k='[\"ocp4-prod-c-site4\",\"acme\"]']").click(); pg.wait_for_timeout(350)
    ok("Fleet defaults not applied here" in pg.inner_text("#sheet") and "overr" in pg.inner_text("#sheet") and "excluded here" in pg.inner_text("#sheet") and "exclusions.yaml" in pg.inner_text("#sheet"), "excluded fleet default listed as not applied")
    pg.keyboard.press("Escape")
    ok(not pg.errs, "provenance: no console errors")

    # 12. charts view toggle (two tenants on one cluster)
    pg = page(); pg.goto(P + "#tab=clusters")
    pg.locator("tr.r:has(.name:text-is('ocp4-prod-b-site1')) td.nm button.cb").click(); pg.wait_for_timeout(350)
    ok(pg.locator("#sview").is_visible() and pg.locator("#sheet section.tsec h3 .tn").all_inner_texts() == ["acme", "beta"], "two tenants: toggle visible, sections per tenant")
    pg.locator("#sview button", has_text="By chart").click()
    ok(pg.locator("#sview button[aria-pressed=true]").inner_text() == "By chart" and "2 tenants" in pg.inner_text("#sheet") and pg.locator("#sheet .chh .cn").all_inner_texts().count("acme") >= 1 and pg.evaluate("document.activeElement.textContent") == "By chart", "By chart groups the same chart across tenants")
    pg.locator("#sview button", has_text="By tenant").click()
    ok(pg.locator("#sheet section.tsec h3 .tn").all_inner_texts() == ["acme", "beta"], "toggle back to tenant sections")
    pg.keyboard.press("Escape")
    pg.locator("td.cell button.cb").first.click(); pg.wait_for_timeout(300)
    ok(pg.locator("#sview").is_hidden(), "single-tenant sheet has no toggle")

