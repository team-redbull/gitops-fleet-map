    # 14. mobile: chart expanded in the bottom sheet
    pg = page(390, 844); pg.goto(P + "#tenant=acme&tab=clusters")
    pg.locator("[data-k='[\"ocp4-prod-a-site1\",\"acme\"]']").click(); pg.wait_for_timeout(400)
    for n in ("vals", "overr"):
        row(n).locator("button.chh").click()
    pg.wait_for_timeout(200)
    bx = pg.locator("#sheet").bounding_box()
    ok(pg.evaluate("document.documentElement.scrollWidth") <= 390 and pg.evaluate("document.querySelector('#sbody').scrollWidth <= document.querySelector('#sbody').clientWidth") and bx["width"] <= 390 and bx["y"] + bx["height"] <= 845, "no horizontal scroll at 390px with charts expanded")
    pg.keyboard.press("Escape")
    pg.locator("button.shs[data-site=site1]").click(); pg.wait_for_timeout(400)
    ok(pg.evaluate("document.documentElement.scrollWidth") <= 390 and pg.evaluate("document.querySelector('#sbody').scrollWidth <= document.querySelector('#sbody').clientWidth"), "no horizontal scroll at 390px in the site sheet")
    ok(pg.evaluate("document.documentElement.scrollWidth") <= 390 and not pg.errs, "mobile folded/site view: no errors")

